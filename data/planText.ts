export type PlanKey = "free" | "plus" | "pro";

// KEEP THESE IN SYNC with the SQL functions plan_price() and plan_limit()
export const PRICES = {
    plus: { LKR: 99, USD: 1 },
    pro: { LKR: 1990, USD: 9 },
} as const;

export const LIMITS: Record<
    PlanKey,
    { videos: number; listings: number; articles: number }
> = {
    free: { videos: 2, listings: 1, articles: 2 },
    plus: { videos: 10, listings: 1, articles: 10 },
    pro: { videos: 50, listings: 5, articles: 50 },
};

export function totalPrice(
    plan: "plus" | "pro",
    currency: "LKR" | "USD",
    months: number,
) {
    return PRICES[plan][currency] * (months === 12 ? 10 : months);
}

export function effectivePlan(
    plan: string | null | undefined,
    expires: string | null | undefined,
): PlanKey {
    if (
        (plan === "plus" || plan === "pro") &&
        expires &&
        new Date(expires) > new Date()
    ) {
        return plan;
    }
    return "free";
}

